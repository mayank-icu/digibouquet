/** Detect country from IP (falls back to 'US'). */
export const detectCountryFromIP = async () => {
  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), 8000);

  try {
    // Primary API: ipapi.co - only fetch country code for faster response
    const response = await fetch('https://ipapi.co/country/', { 
      signal: controller.signal,
      headers: { 
        'Accept': 'text/plain',
        'User-Agent': 'DigiBouquet/1.0'
      }
    });
    
    if (response.ok) {
      const countryCode = (await response.text()).trim();
      if (countryCode && countryCode.length === 2) {
        clearTimeout(timeoutId);
        return countryCode;
      }
    }
  } catch {
    // Silently handle primary API failure
  }

  try {
    // Fallback API: ip-api.com
    const fallbackResponse = await fetch('https://ip-api.com/json/?fields=countryCode', { 
      signal: controller.signal,
      headers: { 
        'Accept': 'application/json',
        'User-Agent': 'DigiBouquet/1.0'
      }
    });
    
    if (fallbackResponse.ok) {
      const fallbackData = await fallbackResponse.json();
      if (fallbackData.countryCode && fallbackData.countryCode.length === 2) {
        clearTimeout(timeoutId);
        return fallbackData.countryCode;
      }
    }
  } catch {
    // Silently handle fallback API failure
  }

  try {
    // Third API: ipwhois.app
    const thirdResponse = await fetch('https://ipwhois.app/json/', { 
      signal: controller.signal,
      headers: { 
        'Accept': 'application/json',
        'User-Agent': 'DigiBouquet/1.0'
      }
    });
    
    if (thirdResponse.ok) {
      const thirdData = await thirdResponse.json();
      if (thirdData.country_code && thirdData.country_code.length === 2) {
        clearTimeout(timeoutId);
        return thirdData.country_code;
      }
    }
  } catch {
    // Silently handle third API failure
  } finally {
    clearTimeout(timeoutId);
  }
  
  // Default fallback
  return 'US';
};

/** Return the ordered app list for a country (max 7 + 'others'). */
export const getAppsForCountry = (countryCode) => {
  const prefs = COUNTRY_APP_PREFERENCES[countryCode] ?? COUNTRY_APP_PREFERENCES.US;
  return prefs.apps;
};

/** Return the display name for a country code. */
export const getCountryName = (countryCode) => {
  const prefs = COUNTRY_APP_PREFERENCES[countryCode];
  return prefs ? prefs.name : 'Unknown';
};

/** Get flag emoji for a country code. */
export const getCountryFlag = (countryCode) => {
  if (!countryCode || countryCode.length !== 2) return '🌍';
  const codePoints = countryCode
    .toUpperCase()
    .split('')
    .map(char => 127397 + char.charCodeAt());
  return String.fromCodePoint(...codePoints);
};

/** Return all countries sorted alphabetically by name. */
export const getAllCountries = () =>
  Object.entries(COUNTRY_APP_PREFERENCES)
    .map(([code, data]) => ({ code, name: data.name, flag: getCountryFlag(code) }))
    .sort((a, b) => a.name.localeCompare(b.name));